const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('tdocDesktop', Object.freeze({
  isDesktop: true,
  getInfo: () => ipcRenderer.invoke('project:info'),
  loadProject: () => ipcRenderer.invoke('project:load'),
  saveProject: (content) => ipcRenderer.invoke('project:save', content),
  saveDraft: (content) => ipcRenderer.invoke('project:save-draft', content),
  discardDraft: () => ipcRenderer.invoke('project:discard-draft'),
  validateProject: () => ipcRenderer.invoke('project:validate'),
  generateProject: () => ipcRenderer.invoke('project:generate'),
  buildPreview: () => ipcRenderer.invoke('project:build'),
  openPreview: () => ipcRenderer.invoke('project:preview'),
  openPreviewAt: (sceneId, nodeId) => ipcRenderer.invoke('project:preview-at', sceneId, nodeId),
  revealProject: () => ipcRenderer.invoke('project:reveal'),
  chooseContent: () => ipcRenderer.invoke('project:choose-content'),
  chooseProjectFolder: () => ipcRenderer.invoke('project:choose-folder'),
  createProjectFolder: () => ipcRenderer.invoke('project:create-folder'),
  getDiagnostics: () => ipcRenderer.invoke('project:diagnostics'),
  listHistory: () => ipcRenderer.invoke('project:history-list'),
  restoreHistory: (historyId) => ipcRenderer.invoke('project:history-restore', historyId),
  getRecoveryStatus: () => ipcRenderer.invoke('project:recovery-status'),
  activateContentForTest: (path) => ipcRenderer.invoke('project:e2e-activate', path),
  chooseAssets: (kind) => ipcRenderer.invoke('assets:choose', kind),
  importAssets: (files, kind) => ipcRenderer.invoke('assets:import', Array.from(files ?? []).map((file) => webUtils.getPathForFile(file)).filter(Boolean), kind),
}));
